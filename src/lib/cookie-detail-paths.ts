const rankById = new Map(
  tierRanks.flatMap((rank) => tierList[rank].map((id) => [id, rank] as const)),
);

export const cookieDetailRoutes = cookies.map(({ id }) => {
  const slug = slugsById[id];
  if (!slug) throw new Error(`Missing detail slug for ${id}`);
  return { id, slug, path: `/cookies/${slug}/`, rank: rankById.get(id) };
});

export const cookieDetailPathById = new Map(cookieDetailRoutes.map(({ id, path }) => [id, path]));
